-- ============================================================
-- 02. 활동 종류와 건수: 이 데이터에 "무슨 일"이 몇 번 기록돼 있나?
-- ============================================================
-- 질문    : 활동(activity)이 몇 종류이고, 각각 몇 번 일어났나?
-- 왜 하나 : 데이터를 이해하는 첫걸음. 숫자끼리 비교하면 질문이 나온다.
--           예) 입고 220,629 > 품목 217,406 → 한 품목이 나눠서 입고된 경우가 있다
--           예) 지급 보류 해제 54,458 vs 설정 52 → "왜 걸렸는지"는 기록이 거의 없다
-- 결과    : 28종 → notes/data_understanding.md 6-2절 (업무 단계별로 정리)
-- 읽는 법 : 많이 일어난 순서로 나온다. 품목 수(217,406)와 비교하며 본다.
-- ============================================================

SELECT activity,          -- 활동 이름 (예: Record Goods Receipt = 입고 기록)
       count(*) AS n      -- 그 활동이 기록된 횟수
FROM events
GROUP BY activity         -- 활동 이름별로 묶어서
ORDER BY n DESC;          -- 많은 순으로 정렬
